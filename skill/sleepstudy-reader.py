# Standard Windows Modern Standby session type definitions
SESSION_TYPES = {
    0: "Active",
    1: "Screen Off",
    2: "Sleep (S0 Low Power Idle)",
    3: "Standby",
    4: "Hybrid Sleep",
    5: "Hibernate (S4)",
    6: "Hybrid Shutdown",
    7: "Shutdown (S5)",
    8: "System Sleep Transition (Unknown)",
    9: "Abnormal Shutdown",
    10: "BugCheck (BSOD)",
    11: "Report Generated"
}

def read_file_detect_encoding(filepath):
    """Reads a file with automatic encoding detection (UTF-16LE vs UTF-8)."""
    with open(filepath, 'rb') as f:
        raw = f.read()
    
    # Check for UTF-16LE BOM or null-byte patterns
    if raw.startswith(b'\xff\xfe') or (len(raw) > 2 and raw[1] == 0 and raw[3] == 0):
        try:
            return raw.decode('utf-16le', errors='replace')
        except Exception:
            pass
    
    # Fallback to UTF-8
    try:
        return raw.decode('utf-8', errors='replace')
    except Exception:
        return raw.decode('latin1', errors='replace')

def parse_modern_spr_data(html_content):
    """
    Extracts and decodes the embedded JavaScript JSON `LocalSprData`
    found in modern Windows 11 SleepStudy / System Power Reports.
    """
    start_marker = 'var LocalSprData = '
    pos1 = html_content.find(start_marker)
    if pos1 == -1:
        return None
    pos1 += len(start_marker)
    
    # Find matching termination
    end_markers = [';\n       var SourceElement', '; var SourceElement', ';\n']
    pos2 = -1
    for em in end_markers:
        pos2 = html_content.find(em, pos1)
        if pos2 != -1:
            break
            
    if pos2 == -1:
        raw_js = html_content[pos1:].strip()
    else:
        raw_js = html_content[pos1:pos2].strip()

    # Clean single-quoted string literals generated by Windows SPR builder:
    # e.g.: {"Key":"EventLog.BootAppStatus","Value":'0x0'} -> "Value":"0x0"
    cleaned_json = re.sub(r":'([^']*?)'", r':"\1"', raw_js)
    
    # Trim trailing non-JSON characters if any
    while cleaned_json and cleaned_json[-1] not in ']}':
        cleaned_json = cleaned_json[:-1]
        
    decoder = json.JSONDecoder()
    try:
        data, _ = decoder.raw_decode(cleaned_json)
        return data
    except Exception as e:
        print(f"[-] Warning: Failed to parse LocalSprData JSON: {e}", file=sys.stderr)
        return None

def parse_legacy_sleepstudy_html(html_content):
    """
    Parses legacy table-based SleepStudy reports using BeautifulSoup.
    """
    soup = BeautifulSoup(html_content, 'html.parser')
    sessions = []
    
    tables = soup.find_all('table')
    for table in tables:
        rows = table.find_all('tr')
        for row in rows:
            cols = [col.get_text(separator=' ').strip() for col in row.find_all(['td', 'th'])]
            if len(cols) >= 5:
                # Check for session row signatures
                if cols[0].isdigit() or "Modern Standby" in cols[1] or "Screen Off" in cols[1]:
                    sessions.append(cols)
    return sessions

def analyze_sleepstudy(filepath):
    """
    Performs forensic analysis on a SleepStudy / SystemPowerReport HTML file.
    """
    print(f"\n========================================================")
    print(f"[*] Analyzing SleepStudy: {os.path.basename(filepath)}")
    print(f"========================================================")
    
    content = read_file_detect_encoding(filepath)
    spr_data = parse_modern_spr_data(content)
    
    if spr_data:
        sys_info = spr_data.get('SystemInformation', {})
        print(f"[+] System: {sys_info.get('SystemManufacturer')} {sys_info.get('SystemProductName')}")
        print(f"[+] BIOS:   {sys_info.get('BIOSVersion')} ({sys_info.get('BIOSDate')})")
        print(f"[+] OS:     Build {sys_info.get('OSBuild')} ({sys_info.get('OSVer')})")
        print(f"[+] Modern Standby Capable: {sys_info.get('ConnectedStandby')}")
        
        instances = spr_data.get('ScenarioInstances', [])
        print(f"\n[+] Total Scenario Instances Logged: {len(instances)}")
        
        print("\n--- Recent Power Transitions (Chronological) ---")
        print(f"{'Session':<8} | {'Type':<22} | {'Duration':<10} | {'Enter Reason':<22} | {'Exit Reason':<20} | {'Blockers'}")
        print("-" * 105)
        
        # Display the most recent 25 sessions
        for s in instances[-25:]:
            sid = s.get('SessionId', '?')
            stype_num = s.get('Type', -1)
            stype_name = SESSION_TYPES.get(stype_num, f"Type {stype_num}")
            
            # Duration in 100ns units -> seconds
            duration_raw = s.get('Duration', 0)
            duration_sec = duration_raw / 10000000.0 if isinstance(duration_raw, (int, float)) else 0.0
            
            if duration_sec >= 60:
                duration_str = f"{duration_sec/60.0:.1f} m"
            else:
                duration_str = f"{duration_sec:.1f} s"
                
            enter_r = s.get('EnterReason', '----')[:22]
            exit_r = s.get('ExitReason', '----')[:20]
            
            # Subsystem Blockers
            blockers = []
            for bg in s.get('BlockerGroups', []):
                for b in bg.get('Blockers', []):
                    bname = b.get('Name')
                    if bname:
                        blockers.append(bname)
                        
            blocker_str = ", ".join(blockers) if blockers else "None"
            
            flag = ""
            if stype_num == 9:
                flag = " [!] ABNORMAL SHUTDOWN"
            elif stype_num == 10:
                flag = " [!] BUGCHECK / CRASH"
            elif stype_num == 2 and duration_sec > 20:
                flag = " (Deep S0ix)"
                
            print(f"{str(sid):<8} | {stype_name:<22} | {duration_str:<10} | {enter_r:<22} | {exit_r:<20} | {blocker_str}{flag}")
            
    else:
        print("[!] Falling back to legacy HTML table parser...")
        sessions = parse_legacy_sleepstudy_html(content)
        print(f"[+] Found {len(sessions)} session table rows:")
        for s in sessions[-20:]:
            print("  | ".join(s[:6]))

def analyze_energy_report(filepath):
    """
    Parses Windows Energy Efficiency Diagnostics (`energy-report.html`).
    """
    print(f"\n========================================================")
    print(f"[*] Analyzing Energy Efficiency Report: {os.path.basename(filepath)}")
    print(f"========================================================")
    
    content = read_file_detect_encoding(filepath)
    soup = BeautifulSoup(content, 'html.parser')
    
    errors = soup.find_all(class_=re.compile(r'error', re.I))
    warnings = soup.find_all(class_=re.compile(r'warning', re.I))
    
    print(f"[+] Summary: {len(errors)} Errors, {len(warnings)} Warnings")
    
    print("\n--- Errors ---")
    for i, err in enumerate(errors, 1):
        txt = err.get_text(separator=' | ').strip()
        lines = [line.strip() for line in txt.split('|') if line.strip()]
        title = lines[0] if lines else "Error"
        desc = lines[1] if len(lines) > 1 else ""
        print(f"[{i}] {title}")
        if desc:
            print(f"    Detail: {desc[:120]}")
            
    print("\n--- Key Warnings ---")
    for i, warn in enumerate(warnings[:10], 1):
        txt = warn.get_text(separator=' | ').strip()
        lines = [line.strip() for line in txt.split('|') if line.strip()]
        title = lines[0] if lines else "Warning"
        print(f"[{i}] {title}")

def analyze_winevents(filepath):
    """
    Parses Windows Event Viewer logs for Kernel-Power, BugChecks, and ACPI events.
    """
    print(f"\n========================================================")
    print(f"[*] Analyzing Windows System Event Log: {os.path.basename(filepath)}")
    print(f"========================================================")
    
    content = read_file_detect_encoding(filepath)
    
    # Key Event Patterns:
    # 506: Screen Off / Modern Standby Enter
    # 507: Screen On / Modern Standby Wake Exit
    # 42:  System Entering Sleep
    # 107: System Resuming from Sleep
    # 41:  Kernel-Power Critical (Reboot without cleanly shutting down first)
    # 1001: BugCheck (Crash dump logged)
    # 6008: Previous system shutdown was unexpected
    
    events_found = []
    
    # 1. Check for PowerShell Format-Table output (TimeCreated ... Id ... Message)
    table_row_re = re.compile(r'^\s*(\d{1,2}[/-]\d{1,2}[/-]\d{2,4}\s+\d{1,2}:\d{2}(?::\d{2})?\s*(?:[AP]M)?)\s+(\d+)\s*(.*)$', re.IGNORECASE)
    lines = content.splitlines()
    is_table = any('TimeCreated' in l and 'Id' in l for l in lines[:5])
    
    if is_table:
        current = None
        for line in lines:
            m = table_row_re.match(line)
            if m:
                if current:
                    events_found.append(current)
                current = {
                    'ts': m.group(1).strip(),
                    'eid': int(m.group(2)),
                    'msg_parts': [m.group(3).strip()] if m.group(3).strip() else []
                }
            elif current:
                if line.strip():
                    current['msg_parts'].append(line.strip())
        if current:
            events_found.append(current)
            
        parsed_events = []
        for ev in events_found:
            msg = ' '.join(ev['msg_parts'])
            reason_match = re.search(r'(?:Sleep Reason|Wake Reason|Reason|Action|BugcheckCode)\s*[:=]\s*([^\r\n.]+)', msg, re.IGNORECASE)
            reason = reason_match.group(1).strip() if reason_match else ""
            if not reason and ev['eid'] == 6008:
                m_shut = re.search(r'shutdown at\s+([^\s]+(?:\s+on\s+[^\s.]+)?)\s+was unexpected', msg, re.IGNORECASE)
                if m_shut:
                    reason = f"at {m_shut.group(1)}"
            parsed_events.append((ev['ts'], ev['eid'], reason, msg))
        events_found = parsed_events
    else:
        # 2. Fallback to Format-List or Event Viewer text/XML exports
        entries = re.split(r'(?=Log Name:|ProviderName:|Event\[\d+\]:|\r?\n\r?\nTimeCreated\s*:)', content)
        for entry in entries:
            if not entry.strip():
                continue
                
            is_relevant = False
            event_id = None
            timestamp = None
            
            id_match = re.search(r'(?:Event ID|Id)\s*[:=]\s*(\d+)', entry, re.IGNORECASE)
            time_match = re.search(r'(?:TimeCreated|Date)\s*[:=]\s*([^\r\n]+)', entry, re.IGNORECASE)
            
            if id_match:
                event_id = int(id_match.group(1))
                if event_id in [41, 42, 107, 109, 506, 507, 1001, 6006, 6008, 14, 0]:
                    is_relevant = True
                    
            if is_relevant:
                if time_match:
                    timestamp = time_match.group(1).strip()
                reason_match = re.search(r'(?:Sleep Reason|Wake Reason|Reason|Action|BugcheckCode)\s*[:=]\s*([^\r\n.]+)', entry, re.IGNORECASE)
                reason = reason_match.group(1).strip() if reason_match else ""
                events_found.append((timestamp, event_id, reason, entry))
            
    print(f"[+] Extracted {len(events_found)} significant power/stability events:")
    print(f"{'Timestamp':<25} | {'Event ID':<10} | {'Type / Description'}")
    print("-" * 75)
    
    for ts, eid, reason, raw in events_found[-30:]:
        desc = ""
        if eid == 506:
            desc = f"Modern Standby Enter ({reason})" if reason else "Modern Standby Enter"
        elif eid == 507:
            desc = f"Modern Standby Wake Exit ({reason})" if reason else "Modern Standby Wake Exit"
        elif eid == 42:
            desc = f"System Sleep ({reason})" if reason else "System Sleep"
        elif eid == 107:
            desc = f"System Resume ({reason})" if reason else "System Resume"
        elif eid == 109:
            desc = f"System Shutdown / Hibernate ({reason})" if reason else "System Shutdown Transition"
        elif eid == 41:
            desc = f"CRITICAL: Kernel-Power Dirty Reboot / Lockup Cutoff"
        elif eid == 1001:
            desc = f"CRITICAL: BugCheck BSOD ({reason})" if reason else "CRITICAL: BugCheck BSOD"
        elif eid == 6008:
            desc = f"CRITICAL: Unexpected Dirty Shutdown ({reason})" if reason else "CRITICAL: Unexpected Dirty Shutdown"
        elif eid == 6006:
            desc = "EventLog Stopped (Clean Shutdown)"
        else:
            desc = f"Driver / Hardware Event ({reason})" if reason else f"Event ID {eid}"
            
        print(f"{str(ts):<25} | {str(eid):<10} | {desc}")

def main():
    parser = argparse.ArgumentParser(description="Windows Modern Standby & Power Telemetry Forensics Tool")
    parser.add_argument("files", nargs="+", help="Files to analyze (.html SleepStudy, energy-report.html, or .txt WinEvents)")
    args = parser.parse_args()
    
    for filepath in args.files:
        if not os.path.exists(filepath):
            print(f"[-] File not found: {filepath}", file=sys.stderr)
            continue
            
        lower_name = filepath.lower()
        if "energy" in lower_name:
            analyze_energy_report(filepath)
        elif "winevent" in lower_name or lower_name.endswith('.txt'):
            # Check if it's systemsleepdiagnostics.txt deprecation notice
            content = read_file_detect_encoding(filepath)
            if "deprecated" in content.lower():
                print(f"\n[*] {os.path.basename(filepath)}: Note: Command deprecated by Windows 11.")
            else:
                analyze_winevents(filepath)
        elif "sleepstudy" in lower_name or "power" in lower_name or lower_name.endswith('.html'):
            analyze_sleepstudy(filepath)
        else:
            # Fallback based on content inspection
            content = read_file_detect_encoding(filepath)
            if "LocalSprData" in content or "SleepStudy" in content:
                analyze_sleepstudy(filepath)
            elif "Energy Efficiency" in content:
                analyze_energy_report(filepath)
            else:
                analyze_winevents(filepath)

if __name__ == '__main__':
    main()
