# Standard Windows Modern Standby session type definitions
SESSION_TYPES = {
    0: "Active",
    1: "Screen Off",
    2: "Sleep (S0 Low Power Idle)",
    3: "Standby",
    4: "Hybrid Sleep",
    5: "Hibernate (S4)",
    6: "Hybrid Shutdown",
    7: "Shutdown (S5)",
    8: "System Sleep Transition (Unknown)",
    9: "Abnormal Shutdown",
    10: "BugCheck (BSOD)",
    11: "Report Generated"
}

def read_file_detect_encoding(filepath):
    """Reads a file with automatic encoding detection (UTF-16LE vs UTF-8)."""
    with open(filepath, 'rb') as f:
        raw = f.read()
    
    # Check for UTF-16LE BOM or null-byte patterns
    if raw.startswith(b'\xff\xfe') or (len(raw) > 2 and raw[1] == 0 and raw[3] == 0):
        try:
            return raw.decode('utf-16le', errors='replace')
        except Exception:
            pass
    
    # Fallback to UTF-8
    try:
        return raw.decode('utf-8', errors='replace')
    except Exception:
        return raw.decode('latin1', errors='replace')

def parse_modern_spr_data(html_content):
    """
    Extracts and decodes the embedded JavaScript JSON `LocalSprData`
    found in modern Windows 11 SleepStudy / System Power Reports.
    """
    start_marker = 'var LocalSprData = '
    pos1 = html_content.find(start_marker)
    if pos1 == -1:
        return None
    pos1 += len(start_marker)
    
    # Find matching termination
    end_markers = [';\n       var SourceElement', '; var SourceElement', ';\n']
    pos2 = -1
    for em in end_markers:
        pos2 = html_content.find(em, pos1)
        if pos2 != -1:
            break
            
    if pos2 == -1:
        raw_js = html_content[pos1:].strip()
    else:
        raw_js = html_content[pos1:pos2].strip()

    # Clean single-quoted string literals generated by Windows SPR builder:
    cleaned_json = re.sub(r":'([^']*?)'", r':"\1"', raw_js)
    
    # Trim trailing non-JSON characters if any
    while cleaned_json and cleaned_json[-1] not in ']}':
        cleaned_json = cleaned_json[:-1]
        
    decoder = json.JSONDecoder()
    try:
        data, _ = decoder.raw_decode(cleaned_json)
        return data
    except Exception as e:
        print(f"[-] Warning: Failed to parse LocalSprData JSON: {e}", file=sys.stderr)
        return None

def parse_legacy_sleepstudy_html(html_content):
    """Parses legacy HTML table-based SleepStudy reports."""
    soup = BeautifulSoup(html_content, 'html.parser')
    sessions = []
    
    tables = soup.find_all('table')
    for table in tables:
        rows = table.find_all('tr')
        for row in rows:
            cols = [td.get_text(strip=True) for td in row.find_all(['td', 'th'])]
            if len(cols) >= 5 and cols[0].isdigit():
                sessions.append({
                    'id': int(cols[0]),
                    'type': cols[1],
                    'start': cols[2],
                    'duration': cols[3],
                    'energy': cols[4] if len(cols) > 4 else "N/A"
                })
    return sessions

def analyze_sleepstudy(filepath):
    """Extracts critical telemetry and failure milestones from SleepStudy HTML reports."""
    print(f"\n========================================================")
    print(f"[*] Analyzing SleepStudy Report: {os.path.basename(filepath)}")
    print(f"========================================================")
    
    content = read_file_detect_encoding(filepath)
    data = parse_modern_spr_data(content)
    
    if data:
        sys_info = data.get("SystemInformation", {})
        print(f"[+] Target System: {sys_info.get('SystemManufacturer', 'Unknown')} {sys_info.get('SystemProductName', 'Unknown')}")
        print(f"[+] BIOS Version:  {sys_info.get('BIOSVersion', 'Unknown')} (Date: {sys_info.get('BIOSReleaseDate', 'Unknown')})")
        print(f"[+] OS Build:      {sys_info.get('OSBuild', 'Unknown')}")
        
        scenarios = data.get("ScenarioInstances") or data.get("Scenarios") or []
        is_instances = "ScenarioInstances" in data
        print(f"\n[+] Total Recorded Power Sessions: {len(scenarios)}")
        print(f"{'Session':<8} | {'Type / State':<22} | {'Duration':<12} | {'Energy Change':<15} | {'Exit / Result'}")
        print("-" * 80)
        
        death_sessions = []
        for s in scenarios[-20:]:  # Print recent sessions
            sid = s.get("SessionId") if "SessionId" in s else s.get("ScenarioId", "?")
            stype_num = s.get("Type") if "Type" in s else s.get("ScenarioType", -1)
            stype = SESSION_TYPES.get(stype_num, f"Type {stype_num}")
            
            # Duration formatting (Windows 11 ScenarioInstances uses microseconds; older SPR uses ms)
            dur_raw = s.get("Duration", 0)
            if is_instances:
                dur_sec = dur_raw / 1_000_000.0 if dur_raw else 0
            else:
                dur_sec = dur_raw / 1000.0 if dur_raw else 0

            if dur_sec >= 3600:
                dur_str = f"{dur_sec/3600:.1f} hours"
            elif dur_sec >= 60:
                dur_str = f"{dur_sec/60:.1f} min"
            else:
                dur_str = f"{dur_sec:.1f} sec"
                
            # Energy
            if is_instances:
                eb = s.get("EntryRemainingCapacity", 0)
                ea = s.get("ExitRemainingCapacity", 0)
            else:
                eb = s.get("EnergyBefore", 0)
                ea = s.get("EnergyAfter", 0)
            ediff = ea - eb
            echg_str = f"{ediff:+,} mWh" if (eb or ea) else "N/A"
            
            # Exit reason / metadata
            entry_reason = s.get("EnterReason") if "EnterReason" in s else s.get("EntryReason", "")
            exit_reason = s.get("ExitReason", "")
            notes = []
            if entry_reason and entry_reason != "----":
                notes.append(f"In: {entry_reason}")
            if exit_reason and exit_reason != "----":
                notes.append(f"Out: {exit_reason}")
            result_str = ", ".join(notes) if notes else "Normal"
            
            # Highlight abnormal terminations
            if stype_num in [9, 10]:
                stype = f"CRITICAL: {stype}"
                death_sessions.append(s)
            elif "Abnormal" in result_str or "BugCheck" in result_str:
                death_sessions.append(s)
                
            print(f"{str(sid):<8} | {stype:<22} | {dur_str:<12} | {echg_str:<15} | {result_str[:25]}")
            
        if death_sessions:
            print("\n" + "!" * 80)
            print("[!] CRITICAL FAILURE SESSIONS DETECTED (Death Sessions):")
            print("!" * 80)
            for ds in death_sessions:
                ds_id = ds.get("SessionId") if "SessionId" in ds else ds.get("ScenarioId")
                ds_type = ds.get("Type") if "Type" in ds else ds.get("ScenarioType")
                ds_raw_dur = ds.get("Duration", 0)
                ds_dur_sec = (ds_raw_dur / 1_000_000.0) if is_instances else (ds_raw_dur / 1000.0)
                ds_entry = ds.get("EnterReason") if "EnterReason" in ds else ds.get("EntryReason")
                ds_start = ds.get("EntryTimestampLocal") or ds.get("StartTime")
                print(f"Session ID: {ds_id}")
                print(f"  Start Time:    {ds_start}")
                print(f"  Duration:      {ds_dur_sec:.2f} seconds")
                print(f"  Scenario Type: {SESSION_TYPES.get(ds_type, ds_type)}")
                print(f"  Entry Reason:  {ds_entry}")
                print(f"  Exit Reason:   {ds.get('ExitReason')}")
                
                # Check 7 orthogonal dimensions if present in Metadata or EventLog
                meta = ds.get("Metadata") or ds.get("EventLog") or {}
                if meta:
                    print("  Environmental Dimensions:")
                    print(f"    - External Monitor: {meta.get('ExternalMonitorState', meta.get('ExternalMonitor', 'N/A'))}")
                    print(f"    - On AC Power:      {ds.get('OnAc', meta.get('OnAc', 'N/A'))}")
                    print(f"    - Lid State:        {meta.get('LidState', 'N/A')}")
                    print(f"    - PDC Checkpoint:   {meta.get('PdcCheckpoint', 'N/A')}")
                    
                # Check blocker devices
                blockers = ds.get("BlockerGroups", [])
                if blockers:
                    print("  Top Power Blockers / Pre-Vetoes:")
                    for b in blockers[:5]:
                        bname = b.get("Name", "Unknown")
                        btime = b.get("ActiveTime", 0) / 1000.0
                        btype = b.get("Type", "")
                        print(f"    - [{btype}] {bname}: Active for {btime:.1f}s")
                print()
    else:
        # Fallback to legacy HTML table
        sessions = parse_legacy_sleepstudy_html(content)
        print(f"[+] Parsed {len(sessions)} legacy table sessions.")
        for s in sessions[-15:]:
            print(f"Session {s.get('id')}: {s.get('type')} | Duration: {s.get('duration')} | Energy: {s.get('energy')}")

def analyze_energy_report(filepath):
    """Parses Windows Energy Efficiency Diagnostics reports."""
    print(f"\n========================================================")
    print(f"[*] Analyzing Energy Diagnostics: {os.path.basename(filepath)}")
    print(f"========================================================")
    
    content = read_file_detect_encoding(filepath)
    soup = BeautifulSoup(content, 'html.parser')
    
    errors = soup.find_all(class_=re.compile(r'error', re.I))
    warnings = soup.find_all(class_=re.compile(r'warning', re.I))
    
    print(f"[+] Summary: {len(errors)} Errors, {len(warnings)} Warnings")
    
    print("\n--- Errors ---")
    for i, err in enumerate(errors, 1):
        txt = err.get_text(separator=' | ').strip()
        lines = [line.strip() for line in txt.split('|') if line.strip()]
        title = lines[0] if lines else "Error"
        desc = lines[1] if len(lines) > 1 else ""
        print(f"[{i}] {title}")
        if desc:
            print(f"    Detail: {desc[:120]}")
            
    print("\n--- Key Warnings ---")
    for i, warn in enumerate(warnings[:10], 1):
        txt = warn.get_text(separator=' | ').strip()
        lines = [line.strip() for line in txt.split('|') if line.strip()]
        title = lines[0] if lines else "Warning"
        print(f"[{i}] {title}")

def analyze_winevents(filepath):
    """
    Parses Windows Event Viewer logs for Kernel-Power, BugChecks, and ACPI events.
    Handles both PowerShell Format-Table and XML/Format-List exports.
    """
    print(f"\n========================================================")
    print(f"[*] Analyzing Windows System Event Log: {os.path.basename(filepath)}")
    print(f"========================================================")
    
    content = read_file_detect_encoding(filepath)
    events_found = []
    
    table_row_re = re.compile(r'^\s*(\d{1,2}[/-]\d{1,2}[/-]\d{2,4}\s+\d{1,2}:\d{2}(?::\d{2})?\s*(?:[AP]M)?)\s+(\d+)\s*(.*)$', re.IGNORECASE)
    lines = content.splitlines()
    is_table = any('TimeCreated' in l and 'Id' in l for l in lines[:10])
    
    if is_table:
        current = None
        for line in lines:
            m = table_row_re.match(line)
            if m:
                if current:
                    events_found.append(current)
                current = {
                    'ts': m.group(1).strip(),
                    'eid': int(m.group(2)),
                    'msg_parts': [m.group(3).strip()] if m.group(3).strip() else []
                }
            elif current:
                if line.strip():
                    current['msg_parts'].append(line.strip())
        if current:
            events_found.append(current)
            
        parsed_events = []
        for ev in events_found:
            msg = ' '.join(ev['msg_parts'])
            reason_match = re.search(r'(?:Sleep Reason|Wake Reason|Reason|Action|BugcheckCode)\s*[:=]\s*([^\r\n.]+)', msg, re.IGNORECASE)
            reason = reason_match.group(1).strip() if reason_match else ""
            if not reason and ev['eid'] == 6008:
                m_shut = re.search(r'shutdown at\s+([^\s]+(?:\s+on\s+[^\s.]+)?)\s+was unexpected', msg, re.IGNORECASE)
                if m_shut:
                    reason = f"at {m_shut.group(1)}"
            parsed_events.append((ev['ts'], ev['eid'], reason, msg))
        events_found = parsed_events
    else:
        entries = re.split(r'(?=Log Name:|ProviderName:|Event\[\d+\]:|\r?\n\r?\nTimeCreated\s*:)', content)
        for entry in entries:
            if not entry.strip():
                continue
                
            is_relevant = False
            event_id = None
            timestamp = None
            
            id_match = re.search(r'(?:Event ID|Id)\s*[:=]\s*(\d+)', entry, re.IGNORECASE)
            time_match = re.search(r'(?:TimeCreated|Date)\s*[:=]\s*([^\r\n]+)', entry, re.IGNORECASE)
            
            if id_match:
                event_id = int(id_match.group(1))
                if event_id in [41, 42, 107, 109, 506, 507, 1001, 6006, 6008, 14, 0]:
                    is_relevant = True
                    
            if is_relevant:
                if time_match:
                    timestamp = time_match.group(1).strip()
                reason_match = re.search(r'(?:Sleep Reason|Wake Reason|Reason|Action|BugcheckCode)\s*[:=]\s*([^\r\n.]+)', entry, re.IGNORECASE)
                reason = reason_match.group(1).strip() if reason_match else ""
                events_found.append((timestamp, event_id, reason, entry))
            
    print(f"[+] Extracted {len(events_found)} significant power/stability events:")
    print(f"{'Timestamp':<25} | {'Event ID':<10} | {'Type / Description'}")
    print("-" * 75)
    
    for ts, eid, reason, raw in events_found[-30:]:
        desc = ""
        if eid == 506:
            desc = f"Modern Standby Enter ({reason})" if reason else "Modern Standby Enter"
        elif eid == 507:
            desc = f"Modern Standby Wake Exit ({reason})" if reason else "Modern Standby Wake Exit"
        elif eid == 42:
            desc = f"System Sleep ({reason})" if reason else "System Sleep"
        elif eid == 107:
            desc = f"System Resume ({reason})" if reason else "System Resume"
        elif eid == 109:
            desc = f"System Shutdown / Hibernate ({reason})" if reason else "System Shutdown Transition"
        elif eid == 41:
            desc = f"CRITICAL: Kernel-Power Dirty Reboot / Lockup Cutoff"
        elif eid == 1001:
            desc = f"CRITICAL: BugCheck BSOD ({reason})" if reason else "CRITICAL: BugCheck BSOD"
        elif eid == 6008:
            desc = f"CRITICAL: Unexpected Dirty Shutdown ({reason})" if reason else "CRITICAL: Unexpected Dirty Shutdown"
        elif eid == 6006:
            desc = "EventLog Stopped (Clean Shutdown)"
        else:
            desc = f"Driver / Hardware Event ({reason})" if reason else f"Event ID {eid}"
            
        print(f"{str(ts):<25} | {str(eid):<10} | {desc}")

def analyze_directory(dirpath):
    """Scans a directory for all relevant diagnostic artifacts and analyzes them in logical order."""
    print(f"\n[*] Scanning directory for diagnostic artifacts: {dirpath}")
    
    dumps = sorted(glob.glob(os.path.join(dirpath, "**", "*.dmp"), recursive=True))
    htmls = sorted(glob.glob(os.path.join(dirpath, "**", "*.html"), recursive=True))
    txts = sorted(glob.glob(os.path.join(dirpath, "**", "*.txt"), recursive=True))
    
    print(f"[+] Found {len(htmls)} HTML report(s), {len(txts)} text log(s), {len(dumps)} crash dump(s).\n")
    
    for h in htmls:
        lower = os.path.basename(h).lower()
        if "energy" in lower:
            analyze_energy_report(h)
        else:
            analyze_sleepstudy(h)
            
    for t in txts:
        lower = os.path.basename(t).lower()
        if "winevent" in lower or "event" in lower or "systempower" in lower:
            analyze_winevents(t)
            
    for d in dumps:
        if parse_minidump:
            parse_minidump(d)
        else:
            print(f"[-] Minidump {d} found, but parse_minidump module not loaded.")

def main():
    parser = argparse.ArgumentParser(description="Windows Modern Standby & Power Telemetry Forensics Tool")
    parser.add_argument("paths", nargs="+", help="Files or directories to analyze (.html SleepStudy, .txt WinEvents, or .dmp Crash Dumps)")
    args = parser.parse_args()
    
    for p in args.paths:
        if not os.path.exists(p):
            print(f"[-] Path not found: {p}", file=sys.stderr)
            continue
            
        if os.path.isdir(p):
            analyze_directory(p)
            continue
            
        lower_name = p.lower()
        if lower_name.endswith('.dmp'):
            if parse_minidump:
                parse_minidump(p)
            else:
                print(f"[-] Error: Cannot parse {p}; parse_minidump module not available.")
        elif "energy" in lower_name:
            analyze_energy_report(p)
        elif "winevent" in lower_name or lower_name.endswith('.txt'):
            content = read_file_detect_encoding(p)
            if "deprecated" in content.lower():
                print(f"\n[*] {os.path.basename(p)}: Note: Command deprecated by Windows 11.")
            else:
                analyze_winevents(p)
        elif "sleepstudy" in lower_name or "power" in lower_name or lower_name.endswith('.html'):
            analyze_sleepstudy(p)
        else:
            # Content-based heuristic
            with open(p, 'rb') as f:
                head = f.read(16)
            if head.startswith(b"PAGE") and b"DU64" in head:
                if parse_minidump:
                    parse_minidump(p)
                else:
                    print(f"[-] Kernel dump signature detected in {p}, but parser unavailable.")
            else:
                content = read_file_detect_encoding(p)
                if "LocalSprData" in content or "SleepStudy" in content:
                    analyze_sleepstudy(p)
                elif "Energy Efficiency" in content:
                    analyze_energy_report(p)
                else:
                    analyze_winevents(p)

if __name__ == '__main__':
    main()
